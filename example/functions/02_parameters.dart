//   • обязательные позиционные — по порядку;
//   • [ ] — необязательные позиционные;
//   • { } — именованные: необязательные или required;
//   • перегрузки функций в Dart нет: одно имя — одна функция,
//     разные варианты вызова дают [ ] и { }.

void main() {
  // Обязательные позиционные ──
  print(sum(2, 3));

  // Необязательные параметры [ ] ──
  // = 1 — значение по умолчанию; без него тип должен допускать null.
  order('Чай');
  order('Пирог', 2);

  // Именованные параметры { } ──
  // передаются по имени, порядок не важен; так задают параметры виджетов во Flutter.
  signUp(email: 'a@b.ru');
  signUp(age: 19, email: 'c@d.ru');

  // Нет перегрузки ──
  // вторую функцию greet с другими параметрами объявить нельзя:
  // вместо неё — необязательный именованный параметр.
  greet('Аня');
  greet('Боря', times: 2);
}

int sum(int a, int b) => a + b;

void order(String dish, [int count = 1]) {
  print('$dish × $count');
}

void signUp({required String email, String city = 'Казань', int? age}) {
  print('$email, $city, $age');
}

void greet(String name, {int times = 1}) {
  for (var i = 0; i < times; i++) {
    print('Привет, $name!');
  }
}
