void main() {
  // 0.1 + 0.2 ──
  // 0.1 нельзя точно записать в двоичном виде.
  print(0.1 + 0.2);
  print(0.1 + 0.2 == 0.3);

  // Сравнение с допуском ──
  // деньги считают в копейках — в int.
  print(((0.1 + 0.2) - 0.3).abs() < 1e-9);
  var priceInKopecks = 10 + 20;
  print('${priceInKopecks / 100} ₽');
}
